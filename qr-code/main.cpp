    int* binToBase4(const int* l1, const int* l2) {
        static int base4[ROWS];
        for (int i = 0; i < ROWS; i++) {
            if (l1[i] == 0 && l2[i] == 0) {
                base4[i] = 0;
            } else if (l1[i] == 0 && l2[i] == 1) {
                base4[i] = 1;
            } else if (l1[i] == 1 && l2[i] == 0) {
                base4[i] = 2;
            } else if (l1[i] == 1 && l2[i] == 1) {
                base4[i] = 3;
            }
        }

        return base4;
    }

    void display2D(const int* l, int size) {
        for (int i = 0; i < size; i++) {
            cout << l[i] << " ";
        }
        cout << endl;
    }

    string base4ToString(const int* base4, int size) {
        string result;
        int chars[4] = {32, 220, 223, 219};
        for (int i = 0; i < size; ++i) {
            result += static_cast<char>(chars[base4[i]]);
        }
        return result + '\n';
    }

    string matrixToString(const int m[ROWS][COLS], int rows, int cols) {
        string result;
        for (int i = 0; i < rows; i += 2) {
            if (i + 1 < rows) {
                const int* l1 = m[i];
                const int* l2 = m[i + 1];
                int* base4 = binToBase4(l1, l2);
                display2D(base4, cols);
                result += base4ToString(base4, cols);
            }
        }
        return result;
    }

