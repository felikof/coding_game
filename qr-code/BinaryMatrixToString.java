    public static String binaryMatrixToString(int[][] matrix) {
        StringBuilder sb = new StringBuilder();
        
        // Caractères pour les valeurs binaires
        char charForOne = '^';  // Utilisé pour le '1'
        char charForZero = '#'; // Utilisé pour le '0'

        for (int i = 0; i < matrix.length; i++) {
            for (int j = 0; j < matrix[i].length; j++) {
                // Choisir le caractère basé sur la valeur binaire
                if (matrix[i][j] == 1) {
                    sb.append(charForOne);
                } else {
                    sb.append(charForZero);
                }
            }
            sb.append('\n');
        }
        return sb.toString();
    }

